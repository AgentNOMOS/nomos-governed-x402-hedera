/**
 * NOMOS Governed x402 — demo page renderer.
 *
 * Reads one frozen global (`__NOMOS_EVIDENCE__`, produced by
 * `apps/demo-ui/src/build.ts`) and renders it. Everything it does is read-only:
 *
 *   - it makes no network request of any kind;
 *   - it has no wallet, no signer and no payment path;
 *   - it cannot create, re-create or alter a receipt;
 *   - the only cryptography is SHA-256 over a canonical form, used to *check*
 *     a digest the page already displays.
 *
 * It also refuses to render. If the evidence module is missing, malformed, or
 * disagrees with itself on a bound field, the page shows an explicit failure
 * instead of a partially-filled success. A demo that renders green ticks over
 * absent data is worse than one that renders nothing.
 */
(function () {
  "use strict";

  var doc = document;
  var live = doc.getElementById("live");

  // ── Utilities ─────────────────────────────────────────────────────────

  function get(obj, path) {
    var cur = obj;
    var parts = path.split(".");
    for (var i = 0; i < parts.length; i += 1) {
      if (cur === null || typeof cur !== "object") return undefined;
      cur = cur[parts[i]];
    }
    return cur;
  }

  function el(tag, className, text) {
    var node = doc.createElement(tag);
    if (className) node.className = className;
    if (text !== undefined && text !== null) node.textContent = String(text);
    return node;
  }

  function announce(message) {
    if (live) live.textContent = message;
  }

  function stateClass(state) {
    return "is-" + (state || "neutral");
  }

  // ── Fail-closed gate ──────────────────────────────────────────────────

  /** Paths that must be present and non-empty before anything renders. */
  var REQUIRED = [
    "chain.transaction_id",
    "chain.transaction_status",
    "chain.consensus_timestamp",
    "chain.memo",
    "chain.quote_id",
    "chain.amount_display",
    "chain.payer",
    "chain.payee",
    "chain.network",
    "chain.settlement_source",
    "chain.hashscan_url",
    "chain.mirror_url",
    "receipt.receipt_id",
    "receipt.record_digest",
    "receipt.verdict",
    "receipt.record",
    "anchor.state",
    "anchor.label",
    "failClosed.error",
    "cards",
    "flow",
    "onchain",
    "verification",
    "limitations",
  ];

  function integrityProblem(data) {
    if (!data || typeof data !== "object") {
      return "The evidence module did not load. `evidence-data.js` is generated by " +
        "`node apps/demo-ui/src/build.ts` and must sit beside this page.";
    }
    for (var i = 0; i < REQUIRED.length; i += 1) {
      var value = get(data, REQUIRED[i]);
      if (value === undefined || value === null || value === "" ||
          (Array.isArray(value) && value.length === 0)) {
        return "The evidence module is incomplete: `" + REQUIRED[i] + "` is missing.";
      }
    }
    if (data.chain.memo !== data.chain.quote_id) {
      return "The on-chain memo and the quote id disagree (" + data.chain.memo +
        " vs " + data.chain.quote_id + "). That binding is the claim this page makes, " +
        "so no part of it is shown.";
    }
    if (data.chain.network !== "hedera:testnet") {
      return "The evidence names network `" + data.chain.network +
        "`. This page presents Hedera Testnet evidence only.";
    }
    // The receipt must be UNMODIFIED. This check used to also refuse whenever
    // anchor_status was anything but NOT_YET_ANCHORED, which read an absent
    // field in a signed document as "no anchor exists" — false since CP-H7F,
    // and it would have hidden a confirmed anchor behind a blank page.
    // The anchor now arrives as separate, digest-bound evidence.
    if (data.receipt.anchor !== null) {
      return "The receipt carries an inline anchor field. A signed receipt must never be " +
        "edited to add one — that would change its canonical bytes and break the signature. " +
        "The anchor belongs in separate evidence, so this page will not render.";
    }
    if (!data.anchor || typeof data.anchor.state !== "string") {
      return "The evidence module carries no anchor resolution. `anchor` is produced by " +
        "`apps/demo-ui/src/anchor-model.ts` and must be present even when nothing is anchored.";
    }
    if (data.anchor.state === "CONFIRMED_ON_TESTNET" && data.anchor.network !== "hedera:testnet") {
      return "The anchor claims confirmation on `" + data.anchor.network + "`. This page " +
        "presents Hedera Testnet evidence only.";
    }
    if (data.receipt.mock_settlement !== false) {
      return "The receipt is marked as a mock settlement and does not evidence a real payment.";
    }
    return null;
  }

  // ── Renderers ─────────────────────────────────────────────────────────

  function bindText(data) {
    var nodes = doc.querySelectorAll("[data-bind]");
    for (var i = 0; i < nodes.length; i += 1) {
      var value = get(data, nodes[i].getAttribute("data-bind"));
      if (value === undefined || value === null) continue;
      nodes[i].textContent = String(value);
    }
  }

  function renderCards(data) {
    var list = doc.getElementById("cards");
    if (!list) return;
    data.cards.forEach(function (card) {
      var li = el("li", "card " + stateClass(card.state));
      li.appendChild(el("p", "card-label", card.label));

      var value = el("p", "card-value");
      value.appendChild(el("span", "pip"));
      value.appendChild(el("span", null, card.value));
      li.appendChild(value);

      li.appendChild(el("p", "card-note", card.note));
      list.appendChild(li);
    });
  }

  function renderFlow(data) {
    var list = doc.getElementById("flow-steps");
    if (!list) return;
    data.flow.forEach(function (step) {
      var li = el("li", "step");
      li.id = "step-" + step.id;

      li.appendChild(el("span", "step-no", String(step.index).padStart(2, "0")));

      var body = el("div", "step-body");
      body.appendChild(el("h3", "step-title", step.title));
      body.appendChild(el("p", "step-summary", step.summary));

      var facts = el("dl", "step-facts");
      step.facts.forEach(function (fact) {
        // A long value in a third of a row wraps badly; let it take the row.
        var row = el("div", fact.value.length > 46 ? "wide" : null);
        row.appendChild(el("dt", null, fact.label));
        row.appendChild(el("dd", fact.mono ? "mono" : null, fact.value));
        facts.appendChild(row);
      });
      body.appendChild(facts);
      body.appendChild(el("p", "step-ref", "Evidence: " + step.evidence_ref));

      li.appendChild(body);
      list.appendChild(li);
    });
  }

  function renderFields(data) {
    var list = doc.getElementById("fields");
    if (!list) return;
    data.onchain.forEach(function (field) {
      var row = el("div", "field");
      row.appendChild(el("dt", null, field.label));

      var dd = el("dd");
      dd.appendChild(el("p", "field-val", field.value));
      if (field.hint) dd.appendChild(el("p", "field-hint", field.hint));
      row.appendChild(dd);

      if (field.copyable) row.appendChild(copyButton(field.label, field.value));
      list.appendChild(row);
    });
  }

  function renderMatrix(data) {
    var body = doc.getElementById("matrix-body");
    if (!body) return;
    data.verification.forEach(function (entry) {
      var tr = el("tr");
      tr.appendChild(el("td", "m-check", entry.check));

      var result = el("td", "m-result " + stateClass(entry.state));
      result.appendChild(el("span", null, entry.result));
      tr.appendChild(result);

      tr.appendChild(el("td", "m-detail", entry.detail));
      body.appendChild(tr);
    });
  }

  function renderFailClosed(data) {
    var fc = data.failClosed;

    var points = doc.getElementById("fc-points");
    if (points) {
      fc.consequences.forEach(function (text) {
        points.appendChild(el("li", null, text));
      });
    }

    var log = doc.getElementById("fc-log-body");
    if (log) {
      log.textContent = [
        "HTTP " + fc.http_status,
        "error          " + fc.error,
        "outcome        " + fc.outcome,
        "",
        "recorded settlement, as the verifier read it:",
        "  atomic_amount  " + JSON.stringify(fc.observed.atomic_amount),
        "  payer          " + JSON.stringify(fc.observed.payer),
        "  memo           " + fc.observed.memo,
        "  finality       " + fc.observed.finality,
        "  failure_code   " + fc.observed.failure_code,
        "",
        "delivered      nothing",
        "receipt        none written",
        "second payment none",
      ].join("\n");
    }
  }

  function renderLimits(data) {
    var list = doc.getElementById("limits-list");
    if (!list) return;
    data.limitations.forEach(function (text) {
      list.appendChild(el("li", null, text));
    });
  }

  function renderReceipt(data) {
    var json = doc.getElementById("record-json");
    if (json) json.textContent = JSON.stringify(data.receipt.record, null, 2);

    var sources = doc.getElementById("foot-sources");
    if (sources && data.sources) sources.textContent = data.sources.join(" · ");
  }

  // ── Anchor ────────────────────────────────────────────────────────────

  var LIVE_UNAVAILABLE = "LIVE VERIFICATION UNAVAILABLE";

  /**
   * Classify a live mirror-node read.
   *
   * Mirrors `classifyLiveCheck` in `apps/demo-ui/src/anchor-model.ts`, which is
   * the version under test. The rule both enforce: an unreachable network says
   * nothing about the anchor. This page can be opened from `file://`, where a
   * cross-origin fetch simply cannot succeed, and that must read as "could not
   * check" — never as "not anchored" and never as "invalid".
   */
  function classifyLive(outcome, expectedCanonical) {
    if (outcome.kind === "network_error" || outcome.kind === "http_error") {
      var why = outcome.kind === "http_error"
        ? "the mirror node returned HTTP " + outcome.status
        : "the mirror node could not be reached";
      return {
        state: "LIVE_VERIFICATION_UNAVAILABLE",
        label: LIVE_UNAVAILABLE,
        detail: why + ". This says nothing about the anchor: the verification shown above was " +
          "performed offline against committed evidence and is unaffected.",
      };
    }
    if (!expectedCanonical) {
      return { state: "LIVE_VERIFICATION_UNAVAILABLE", label: LIVE_UNAVAILABLE,
        detail: "no expected message is available to compare against." };
    }
    var decoded;
    try {
      decoded = decodeURIComponent(escape(atob(outcome.messageBase64)));
    } catch (err) {
      return { state: "LIVE_VERIFICATION_UNAVAILABLE", label: LIVE_UNAVAILABLE,
        detail: "the mirror node returned a message that could not be decoded." };
    }
    if (decoded !== expectedCanonical) {
      return { state: "ANCHOR_EVIDENCE_INVALID", label: "ANCHOR EVIDENCE INVALID",
        detail: "the message on the topic differs from the recorded envelope, byte for byte." };
    }
    return { state: "CONFIRMED_ON_TESTNET", label: "CONFIRMED ON HEDERA TESTNET",
      detail: "the message on the topic matches the recorded envelope exactly (" +
        expectedCanonical.length + " bytes)." };
  }

  function renderAnchor(data) {
    var a = data.anchor;
    var box = doc.getElementById("anchor");
    if (!box || !a) return;

    box.setAttribute("data-state", a.state);

    var facts = doc.getElementById("anchor-facts");
    if (facts && a.state === "CONFIRMED_ON_TESTNET") {
      [
        ["Network", "Hedera Testnet", false],
        ["Topic", a.topic_id, true],
        ["Sequence", String(a.sequence_number), true],
        ["Consensus timestamp", a.consensus_timestamp + (a.consensus_utc ? " · " + a.consensus_utc : ""), true],
        ["Submit transaction", a.transaction_id_short, true],
        ["record_digest", a.record_digest_short, true],
        ["Envelope SHA-256", a.envelope_sha256_short, true],
        ["Message size", a.envelope_bytes + " bytes, one chunk", false],
      ].forEach(function (row) {
        if (!row[1]) return;
        var div = doc.createElement("div");
        div.appendChild(el("dt", null, row[0]));
        div.appendChild(el("dd", row[2] ? "mono wrap" : "wrap", row[1]));
        facts.appendChild(div);
      });
    }

    var reasons = doc.getElementById("anchor-reasons");
    if (reasons && a.reasons && a.reasons.length > 0) {
      a.reasons.forEach(function (r) { reasons.appendChild(el("li", null, r)); });
      reasons.hidden = false;
    }

    var link = doc.getElementById("link-topic");
    if (link) link.href = a.hashscan_url;

    var button = doc.getElementById("anchor-live");
    var out = doc.getElementById("anchor-live-out");
    if (!button || !out) return;
    if (a.state !== "CONFIRMED_ON_TESTNET") { button.disabled = true; return; }

    button.addEventListener("click", function () {
      button.disabled = true;
      out.textContent = "Reading the topic…";
      var done = function (v) {
        out.textContent = v.label + " — " + v.detail;
        out.className = "anchor-live-out state-" + v.state.toLowerCase();
        button.disabled = false;
        announce(v.label + ". " + v.detail);
      };
      if (typeof fetch !== "function") {
        done(classifyLive({ kind: "network_error" }, a.envelope_canonical));
        return;
      }
      fetch(a.mirror_url, { headers: { accept: "application/json" } }).then(
        function (res) {
          if (!res.ok) { done(classifyLive({ kind: "http_error", status: res.status }, a.envelope_canonical)); return; }
          return res.json().then(function (body) {
            done(classifyLive({ kind: "fetched", messageBase64: body && body.message }, a.envelope_canonical));
          });
        },
        function () { done(classifyLive({ kind: "network_error" }, a.envelope_canonical)); },
      );
    });
  }

  function renderLinks(data) {
    var mirror = doc.getElementById("link-mirror");
    if (mirror) mirror.href = data.chain.mirror_url;

    var hashscan = doc.getElementById("link-hashscan");
    if (hashscan) hashscan.href = data.chain.hashscan_url;
  }

  // ── Copy to clipboard ─────────────────────────────────────────────────

  function copyButton(label, value) {
    var button = el("button", "copy", "Copy");
    button.type = "button";
    button.setAttribute("aria-label", "Copy " + label);

    button.addEventListener("click", function () {
      writeClipboard(value).then(
        function () {
          mark(button, "done", "Copied", label + " copied to the clipboard");
        },
        function () {
          mark(button, "failed", "Select it", "Copying failed — select the value manually");
        },
      );
    });
    return button;
  }

  function mark(button, state, text, message) {
    button.setAttribute("data-state", state);
    button.textContent = text;
    announce(message);
    window.setTimeout(function () {
      button.removeAttribute("data-state");
      button.textContent = "Copy";
    }, 2200);
  }

  function writeClipboard(value) {
    if (navigator.clipboard && navigator.clipboard.writeText) {
      return navigator.clipboard.writeText(value);
    }
    // `file://` and other non-secure contexts have no async clipboard. Fall back
    // rather than silently doing nothing.
    return new Promise(function (resolve, reject) {
      var area = doc.createElement("textarea");
      area.value = value;
      area.setAttribute("readonly", "readonly");
      area.style.position = "fixed";
      area.style.top = "-1000px";
      doc.body.appendChild(area);
      area.select();
      var ok = false;
      try {
        ok = doc.execCommand("copy");
      } catch (err) {
        ok = false;
      }
      doc.body.removeChild(area);
      if (ok) resolve();
      else reject(new Error("clipboard unavailable"));
    });
  }

  // ── Asset slots ───────────────────────────────────────────────────────

  /**
   * The two architecture graphics are supplied separately. Until a file is
   * present the frame shows a named slot rather than a broken image or an
   * invented substitute diagram.
   */
  function wireAssetSlots() {
    var frames = doc.querySelectorAll("[data-asset-slot]");
    for (var i = 0; i < frames.length; i += 1) {
      (function (frame) {
        var img = frame.querySelector("img");
        var slot = frame.querySelector(".slot");
        if (!img || !slot) return;

        function showSlot() {
          img.hidden = true;
          img.style.display = "none";
          slot.hidden = false;
        }
        if (img.complete) {
          if (img.naturalWidth === 0) showSlot();
        } else {
          img.addEventListener("error", showSlot);
        }
      })(frames[i]);
    }
  }

  // ── In-browser digest recomputation ───────────────────────────────────

  function recomputeRow(state, text) {
    var li = el("li", stateClass(state));
    li.appendChild(el("span", "r-mark", state === "verified" ? "✓" : state === "detected" ? "⛔" : "!"));
    li.appendChild(el("span", null, text));
    return li;
  }

  function wireRecompute(data) {
    var button = doc.getElementById("recompute");
    var out = doc.getElementById("recompute-out");
    if (!button || !out) return;

    var jcs = window.NOMOS_JCS;
    if (!jcs || !window.crypto || !window.crypto.subtle) {
      button.disabled = true;
      var hint = doc.getElementById("recompute-hint");
      if (hint) {
        hint.textContent = "Unavailable here: this browsing context exposes no WebCrypto SHA-256.";
      }
      return;
    }

    button.addEventListener("click", function () {
      button.disabled = true;
      button.textContent = "Recomputing…";
      out.textContent = "";

      var record = data.receipt.record;
      var tampered = JSON.parse(JSON.stringify(record));
      tampered.atomic_amount = "1";

      Promise.all([
        jcs.canonicalDigest(record),
        jcs.canonicalDigest(tampered),
        jcs.receiptId(record.idempotency_key, record.hedera_transaction_id, data.receipt.record_digest),
      ]).then(function (results) {
        var digest = results[0];
        var tamperedDigest = results[1];
        var derivedId = results[2];

        var digestOk = digest === data.receipt.record_digest;
        var idOk = derivedId === data.receipt.receipt_id;
        var tamperCaught = tamperedDigest !== data.receipt.record_digest;

        out.appendChild(recomputeRow(
          digestOk ? "verified" : "pending",
          digestOk
            ? "record_digest recomputed here and it matches: " + digest
            : "record_digest does NOT match. Computed " + digest + ", receipt carries " + data.receipt.record_digest,
        ));
        out.appendChild(recomputeRow(
          idOk ? "verified" : "pending",
          idOk
            ? "receipt_id re-derived from (idempotency key, transaction id, digest): " + derivedId
            : "receipt_id does NOT re-derive. Computed " + derivedId,
        ));
        out.appendChild(recomputeRow(
          tamperCaught ? "detected" : "pending",
          tamperCaught
            ? "Tamper probe: changing atomic_amount to \"1\" yields " + tamperedDigest + " — a different digest, so the signature over it cannot verify."
            : "Tamper probe did not change the digest. Something is wrong with this check.",
        ));

        announce(digestOk && idOk && tamperCaught
          ? "Recomputation finished: digest and receipt id match, tamper probe detected."
          : "Recomputation finished with a mismatch. See the results list.");

        button.textContent = "Recompute again";
        button.disabled = false;
      }, function (error) {
        out.appendChild(recomputeRow("pending", "Recomputation failed: " + (error && error.message ? error.message : "unknown error") + ". No conclusion is drawn from a check that did not run."));
        announce("Recomputation failed.");
        button.textContent = "Recompute digest in this browser";
        button.disabled = false;
      });
    });
  }

  // ── Reveal ────────────────────────────────────────────────────────────

  function stagger() {
    if (window.matchMedia && window.matchMedia("(prefers-reduced-motion: reduce)").matches) return;
    var targets = doc.querySelectorAll(".hero-copy, .seal, .band-head, .binding, .cards, .flow, .fields, .matrix, .compare, .receipt-panel, .fc, .figure, .tenets, .limits, .claim");
    for (var i = 0; i < targets.length; i += 1) {
      targets[i].style.setProperty("--d", Math.min(i, 6) * 70 + "ms");
      targets[i].classList.add("reveal");
    }
  }

  // ── Boot ──────────────────────────────────────────────────────────────

  function boot() {
    var page = doc.querySelector("main.page");
    var alertBox = doc.getElementById("integrity-alert");
    var reason = doc.getElementById("integrity-reason");

    var data = window.__NOMOS_EVIDENCE__;
    var problem = integrityProblem(data);

    if (problem) {
      if (reason) reason.textContent = problem;
      if (alertBox) alertBox.hidden = false;
      if (page) page.hidden = true;
      // Placeholders outside `main` would otherwise sit there as stray dashes,
      // which reads like a value that failed to load rather than one withheld.
      var stale = doc.querySelectorAll("[data-bind]");
      for (var i = 0; i < stale.length; i += 1) stale[i].textContent = "";
      doc.title = "Evidence unavailable — NOMOS Governed x402";
      announce("Evidence unavailable. " + problem);
      return;
    }

    bindText(data);
    renderCards(data);
    renderFlow(data);
    renderFields(data);
    renderMatrix(data);
    renderFailClosed(data);
    renderLimits(data);
    renderReceipt(data);
    renderAnchor(data);
    renderLinks(data);
    wireAssetSlots();
    wireRecompute(data);

    if (page) page.hidden = false;
    stagger();
  }

  if (doc.readyState === "loading") {
    doc.addEventListener("DOMContentLoaded", boot);
  } else {
    boot();
  }
})();
